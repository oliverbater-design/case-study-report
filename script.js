function setupChartFilters() {
  const buttons = document.querySelectorAll("[data-chart-filter]");
  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      buttons.forEach((item) => item.classList.remove("is-active"));
      button.classList.add("is-active");
      renderCharts(button.dataset.chartFilter);
    });
  });
}

function openChart(index) {
  const chart = charts[index];
  const modal = byId("chart-modal");
  if (!chart || !modal) {
    return;
  }

  const image = byId("modal-image");
  if (image) {
    image.src = chart.src;
    image.alt = chart.alt;
  }
  setText("modal-title", chart.title);
  setText("modal-caption", chart.caption);

  if (typeof modal.showModal === "function") {
    modal.showModal();
  } else {
    modal.setAttribute("open", "");
  }
  document.body.classList.add("modal-open");
}

function closeChart() {
  const modal = byId("chart-modal");
  if (!modal) {
    return;
  }
  if (typeof modal.close === "function") {
    modal.close();
  } else {
    modal.removeAttribute("open");
  }
  document.body.classList.remove("modal-open");
}

function setupModal() {
  const modal = byId("chart-modal");
  const closeButton = byId("modal-close");
  if (!modal || !closeButton) {
    return;
  }
  closeButton.addEventListener("click", closeChart);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) {
      closeChart();
    }
  });
  modal.addEventListener("close", () => document.body.classList.remove("modal-open"));
}

setupModal();

