function renderTimeline(countryKey, selectedIndex) {
  const country = countries[countryKey];
  const container = byId("timeline-list");
  if (!country || !container) {
    return;
  }
  activeTimelineIndex = selectedIndex;
  container.innerHTML = country.timeline
    .map(
      (item, index) => `
        <button class="timeline-item ${index === selectedIndex ? "is-active" : ""}" type="button" data-timeline-index="${index}">
          <span class="timeline-year">${item.year}</span>
          <span>
            <strong>${item.title}</strong>
            <span>${item.short}</span>
          </span>
        </button>
      `
    )
    .join("");

  renderTimelineDetail(countryKey, selectedIndex);

  document.querySelectorAll("[data-timeline-index]").forEach((button) => {
    button.addEventListener("click", () => {
      renderTimeline(activeCountry, Number(button.dataset.timelineIndex));
    });
  });
}

function renderTimelineDetail(countryKey, index) {
  const detail = byId("timeline-detail");
  const country = countries[countryKey];
  const event = country && country.timeline[index];
  if (!detail || !event) {
    return;
  }
  detail.innerHTML = `
    <p class="eyebrow">${event.year}</p>
    <h3>${event.title}</h3>
    <p>${event.detail}</p>
    <dl>
      <div>
        <dt>Political logic</dt>
        <dd>${event.politics}</dd>
      </div>
      <div>
        <dt>Institutional result</dt>
        <dd>${event.institution}</dd>
      </div>
    </dl>
  `;
}

function renderCharts(filter = "all") {
  const container = byId("chart-gallery");
  if (!container) {
    return;
  }
  const visibleCharts = charts.filter((chart) => filter === "all" || chart.country === filter);
  container.innerHTML = visibleCharts
    .map(
      (chart) => `
        <article class="chart-card">
          <img src="${chart.src}" alt="${chart.alt}" loading="lazy">
          <div class="chart-card__body">
            ${countryTag(chart.country)}
            <h3>${chart.title}</h3>
            <p>${chart.caption}</p>
            <button type="button" data-chart-index="${charts.indexOf(chart)}">Open chart</button>
          </div>
        </article>
      `
    )
    .join("");

  document.querySelectorAll("[data-chart-index]").forEach((button) => {
    button.addEventListener("click", () => openChart(Number(button.dataset.chartIndex)));
  });
}

