let activeCountry = "nz";
let activeTimelineIndex = 0;

const countryButtons = document.querySelectorAll("[data-country]");
const chartFilterButtons = document.querySelectorAll("[data-chart-filter]");
const lessonFilterButtons = document.querySelectorAll("[data-lesson-filter]");
const chartModal = document.getElementById("chart-modal");

function setTheme(countryKey) {
  const country = countries[countryKey];
  document.documentElement.style.setProperty("--accent", country.accent);
  document.documentElement.style.setProperty("--accent-soft", country.accentSoft);
}

function renderCountry(countryKey) {
  const country = countries[countryKey];
  activeCountry = countryKey;
  activeTimelineIndex = 0;
  setTheme(countryKey);

  document.getElementById("country-kicker").textContent = country.kicker;
  document.getElementById("country-title").textContent = country.title;
  document.getElementById("country-summary").textContent = country.summary;
  document.getElementById("country-period").textContent = country.period;
  document.getElementById("country-government").textContent = country.government;
  document.getElementById("country-question").textContent = country.question;
  document.getElementById("country-diagnosis").textContent = country.diagnosis;
  document.getElementById("featured-chart-image").src = country.featuredChart.src;
  document.getElementById("featured-chart-image").alt = country.featuredChart.alt;
  document.getElementById("featured-chart-caption").textContent = country.featuredChart.caption;
  document.getElementById("timeline-title").textContent = `${country.name} reform timeline`;
  document.getElementById("timeline-intro").textContent = country.timelineIntro;
  document.getElementById("country-quote").textContent = country.quote;
  document.getElementById("country-quote-source").textContent = country.quoteSource;
  document.getElementById("durability-title").textContent = country.durabilityTitle;
  document.getElementById("durability-copy").textContent = country.durabilityCopy;

  document.getElementById("logic-strip").innerHTML = country.logic
    .map((step, index) => `<div class="logic-step"><span>${index + 1}</span>${step}</div>`)
    .join("");

  document.getElementById("stat-grid").innerHTML = country.stats
    .map(
      (stat) => `
        <article class="stat-card">
          <strong>${stat.value}</strong>
          <h3>${stat.label}</h3>
          <p>${stat.text}</p>
        </article>
      `
    )
    .join("");

  renderTimeline(countryKey, 0);
  updateCountryButtons(countryKey);
}

function updateCountryButtons(countryKey) {
  countryButtons.forEach((button) => {
    const selected = button.dataset.country === countryKey;
    button.classList.toggle("is-active", selected);
    button.setAttribute("aria-selected", String(selected));
  });
}

function renderTimeline(countryKey, selectedIndex) {
  const country = countries[countryKey];
  activeTimelineIndex = selectedIndex;
  document.getElementById("timeline-list").innerHTML = country.timeline
    .map(
      (item, index) => `
        <button class="timeline-item ${index === selectedIndex ? "is-active" : ""}" type="button" data-timeline-index="${index}">
          <span class="timeline-year">${item.year}</span>
          <span>
            <strong>${item.title}</strong>
            <span>${item.short}</span>
          </span>
        </button>
      `
    )
    .join("");

  renderTimelineDetail(countryKey, selectedIndex);

  document.querySelectorAll("[data-timeline-index]").forEach((button) => {
    button.addEventListener("click", () => {
      renderTimeline(activeCountry, Number(button.dataset.timelineIndex));
    });
  });
}

function renderTimelineDetail(countryKey, index) {
  const event = countries[countryKey].timeline[index];
  document.getElementById("timeline-detail").innerHTML = `
    <p class="eyebrow">${event.year}</p>
    <h3>${event.title}</h3>
    <p>${event.detail}</p>
    <dl>
      <div>
        <dt>Political logic</dt>
        <dd>${event.politics}</dd>
      </div>
      <div>
        <dt>Institutional result</dt>
        <dd>${event.institution}</dd>
      </div>
    </dl>
  `;
}

function renderComparison() {
  document.getElementById("comparison-grid").innerHTML = comparisons
    .map(
      (item) => `
        <article class="comparison-row">
          <div class="comparison-topic">${item.topic}</div>
          <div>
            <span class="country-tag country-tag--nz">New Zealand</span>
            <p>${item.nz}</p>
          </div>
          <div>
            <span class="country-tag country-tag--sweden">Sweden</span>
            <p>${item.sweden}</p>
          </div>
        </article>
      `
    )
    .join("");
}

function renderCharts(filter = "all") {
  const visibleCharts = charts.filter((chart) => filter === "all" || chart.country === filter);
  document.getElementById("chart-gallery").innerHTML = visibleCharts
    .map(
      (chart, index) => `
        <article class="chart-card">
          <img src="${chart.src}" alt="${chart.alt}" loading="lazy">
          <div class="chart-card__body">
            <span class="country-tag country-tag--${chart.country}">${countries[chart.country].name}</span>
            <h3>${chart.title}</h3>
            <p>${chart.caption}</p>
            <button type="button" data-chart-index="${charts.indexOf(chart)}">Open chart</button>
          </div>
        </article>
      `
    )
    .join("");

  document.querySelectorAll("[data-chart-index]").forEach((button) => {
    button.addEventListener("click", () => openChart(Number(button.dataset.chartIndex)));
  });
}

function renderLessons(filter = "shared") {
  document.getElementById("lesson-list").innerHTML = lessons[filter]
    .map(
      (lesson, index) => `
        <article class="lesson-card">
          <span>${index + 1}</span>
          <h3>${lesson.title}</h3>
          <p>${lesson.text}</p>
        </article>
      `
    )
    .join("");
}

function openChart(index) {
  const chart = charts[index];
  document.getElementById("modal-image").src = chart.src;
  document.getElementById("modal-image").alt = chart.alt;
  document.getElementById("modal-title").textContent = chart.title;
  document.getElementById("modal-caption").textContent = chart.caption;

  if (typeof chartModal.showModal === "function") {
    chartModal.showModal();
  } else {
    chartModal.setAttribute("open", "");
  }
  document.body.classList.add("modal-open");
}

function closeChart() {
  if (typeof chartModal.close === "function") {
    chartModal.close();
  } else {
    chartModal.removeAttribute("open");
  }
  document.body.classList.remove("modal-open");
}

countryButtons.forEach((button) => {
  button.addEventListener("click", () => renderCountry(button.dataset.country));
});

chartFilterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    chartFilterButtons.forEach((item) => item.classList.remove("is-active"));
    button.classList.add("is-active");
    renderCharts(button.dataset.chartFilter);
  });
});

lessonFilterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    lessonFilterButtons.forEach((item) => item.classList.remove("is-active"));
    button.classList.add("is-active");
    renderLessons(button.dataset.lessonFilter);
  });
});

document.getElementById("modal-close").addEventListener("click", closeChart);
chartModal.addEventListener("click", (event) => {
  if (event.target === chartModal) {
    closeChart();
  }
});
chartModal.addEventListener("close", () => document.body.classList.remove("modal-open"));

renderComparison();
renderCharts();
renderLessons();
renderCountry(activeCountry);
